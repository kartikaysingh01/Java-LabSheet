public class InheritanceConceptMain {

    public static void main(String[] args) {

        System.out.println("Multiple and Hybrid Inheritance in Java");
        System.out.println("Java does not support multiple inheritance using classes.");
        System.out.println("A class cannot extend two classes at the same time.");
        System.out.println("Example of invalid syntax: class C extends A, B");
        System.out.println("Hybrid inheritance combines more than one inheritance type.");
        System.out.println("Interfaces are commonly used when multiple or hybrid");
        System.out.println("inheritance of type or behavior is required.");
    }

    /*
     Multiple Inheritance:
     A class cannot extend two classes in Java.

     Invalid example:
     class C extends A, B

     Hybrid Inheritance:
     It is a combination of different types of inheritance.

     Java commonly uses interfaces to achieve multiple or
     hybrid inheritance of type or behavior.

     Interfaces are not created or implemented in this program
     because this question is concept-only.
    */
}